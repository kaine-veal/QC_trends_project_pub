def list_available_months(run_type: str):
    """
    List all available archived months for a given run type.
    
    Args:
        run_type: Type of run (genotyping, racp, panels)
    """
    archive_path = ARCHIVE_BASE / run_type
    
    if not archive_path.exists():
        print(f"No archive found for run type: {run_type}")
        print(f"Expected location: {archive_path}")
        return
    
    months = sorted([d.name for d in archive_path.iterdir() if d.is_dir()])
    
    if not months:
        print(f"No archived months found for run type: {run_type}")
        return
    
    print(f"\nAvailable archived months for {run_type}:")
    print("=" * 50)
    for month in months:
        multiqc_path = archive_path / month / "multiqc_output" / "multiqc_data"
        if multiqc_path.exists():
            print(f"  ✓ {month}")
        else:
            print(f"  ✗ {month} (incomplete - missing MultiQC data)")
    print()

def main():
    ap = argparse.ArgumentParser(
        description="Build QC CSV from archived MultiQC results and generate Excel + PNG reports.",
    )
    ap.add_argument("--run-type", 
                    choices=["genotyping", "racp", "panels"], 
                    required=True,
                    help="Run type for analysis")
    
    ap.add_argument("--months", 
                    type=str, 
                    help="Comma-separated list of months in YYYY-MM format (e.g., 2025-01,2025-02)")
    
    ap.add_argument("--metrics", 
                    default="all", 
                    help="Comma-separated list of metrics or 'all' (default: all)")
    
    ap.add_argument("--list-months", 
                    action="store_true",
                    help="List all available archived months for the specified run type")
    
    args = ap.parse_args()
    
    # Handle --list-months flag
    if args.list_months:
        list_available_months(args.run_type)
        return
    
    # Validate that --months is provided when not listing
    if not args.months:
        ap.error("--months is required (unless using --list-months)")
    
    # Parse the months
    months = [m.strip() for m in args.months.split(",")]
    
    # Validate month format
    for month in months:
        try:
            datetime.strptime(month, "%Y-%m")
        except ValueError:
            logger.error(f"Invalid month format: {month}")
            raise SystemExit(f"Error: Month '{month}' is not in YYYY-MM format")
    
    logger.info(f"Starting QC report generation for {args.run_type} - months: {months}")
    
    # Set up output directory in project root under month_1_output
    project_root = Path(__file__).resolve().parent.parent.parent.parent.parent
    base_dir = project_root / "month_1_output"

    # Pick subfolder + file stem by run type
    if args.run_type == "racp":
        out_dir = base_dir / "racp_output"
        file_stem = "racp_qc_trends"
    elif args.run_type == "genotyping":
        out_dir = base_dir / "genotyping_output"
        file_stem = "genotyping_qc_trends"
    elif args.run_type == "panels":
        out_dir = base_dir / "panels_output"
        file_stem = "panels_qc_trends"
    else:
        out_dir = base_dir / "tmp_table_graph"
        file_stem = "qc_trends"

    out_dir.mkdir(parents=True, exist_ok=True)
    
    # If multiple months, add month range to filename
    if len(months) > 1:
        file_stem = f"{file_stem}_{months[0]}_to_{months[-1]}"
    else:
        file_stem = f"{file_stem}_{months[0]}"
    
    # Add metrics suffix if not "all"
    if args.metrics.lower() != "all":
        # Shorten metric names for filename
        metric_list = [m.strip() for m in args.metrics.split(",")]
        if len(metric_list) <= 3:
            # If 3 or fewer metrics, include all names
            metrics_suffix = "_".join(metric_list)
        else:
            # If more than 3, just say "custom"
            metrics_suffix = "custom"
        file_stem = f"{file_stem}_{metrics_suffix}"

    # Build CSV (single month or combined)
    csv_path = out_dir / f"{file_stem}.csv"
    
    if len(months) == 1:
        logger.info(f"Processing single month: {months[0]}")
        build_csv_from_month(args.run_type, months[0], csv_path)
    else:
        logger.info(f"Processing {len(months)} months: {', '.join(months)}")
        combine_monthly_csvs(args.run_type, months, csv_path)
    
    # Build reports
    out_png = out_dir / f"{file_stem}.png"
    make_report(
        long_csv=csv_path,
        out_png=out_png,
        run_type=args.run_type,
        metrics=args.metrics,
        out_dir=out_dir
    )
    
    logger.info("QC report generation completed successfully")
    print(f"\n{'='*60}")
    print("✓ Report generation complete!")
    print(f"{'='*60}")

if __name__ == "__main__":
    main()
    