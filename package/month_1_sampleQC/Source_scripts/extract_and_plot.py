RUN_DATE_CAPTURE = re.compile(r'^(?P<date>\d{6})_') # Captures the date at the start of run folder name

def parse_run_date(date_string: str) -> Optional[datetime]:
    """
    Parses a date string in YYMMDD format and returns a datetime object if valid, otherwise None 
    """
    try:
        dt = datetime.strptime(date_string, "%y%m%d") # Parse date in YYMMDD format
        if 2000 <= dt.year <= 2100: # Sanity check to exclude invalid years
            return dt # Return datetime object if valid
    except ValueError: # Error raised if date_string is not in the expected format for any run
        return None
    return None # If YYMMDD is parsed but year out of range, return None

def build_sample_path_map(sources_txt_path: Path) -> Dict[str, List[str]]:
    """
    Function which takes a path to multiqc_sources.txt and returns a dictionary, mapping sample keys to a list of file paths.
    This means that the sample key, e.g. 436768311_S5_L001_R1_001, can later be used to link to the original file paths. So, the resulting
    dictionary will take the sample key (436768311_S5_L001_R1_001) as the key, and the value as the corresponding path
    """
    sources_map: Dict[str, List[str]] = {} # Initialise an empty dictionary to hold the mapping
    # Open the text file (one path per line or "label: path" format)
    with sources_txt_path.open("r", encoding="utf-8") as f: # Read the sources.txt file line by line
        for raw_line in f: 
            line = raw_line.strip() # Trim whitespace/newlines
            if not line: # Skip blank lines
                continue
            if "fastqc" not in line.lower(): # Only process lines mentioning FastQC outputs
                continue

            columns = line.split() # Splits each line in sources.txt into separate columns based on vertical whitespace
            source_path = columns[-1] # Take the last column as the source path (e.g. where e.g. 436768311_S5_L001_R1_001 would be expected to be)
            source_path_no_extension = Path(source_path).stem # Removes the file extension (e.g. .zip)
            sample_key = re.sub(r"_fastqc$", "", source_path_no_extension) # Normalise to a sample key by removing trailing "_fastqc"

            if sample_key not in sources_map: # Check if the sample key is already in the dictionary
                sources_map[sample_key] = []   # If not, create a new entry with an empty list
            sources_map[sample_key].append(source_path)  # Append the source path to the list for this sample key

    return sources_map # Return the completed mapping dictionary

def infer_run_from_path(file_path: str) -> Tuple[Optional[str], Optional[datetime]]:
    """
    This function takes a file path (from the dict value generated by build_sample_path_map, looks at the parent folder name, 
    e.g. 250101_M00000_0001_000000000-ABCDE, and extracts the run date from it if it begins with YYMMDD. Then, returns the parent
    folder name and the parsed run date.
    """
    try:
        parent_folder = Path(file_path).parent.name  # Gets the parent directory name of each file path within multiqc_sources.txt
    except Exception:
        parent_folder = None # If the path is invalid, set parent to None
    if parent_folder:
        date_match = RUN_DATE_CAPTURE.match(parent_folder) # Try to match the folder name against the RUN_DATE_CAPTURE regex, whether it begins with YYMMDD 
        if date_match:
            return parent_folder, parse_run_date(date_match.group("date")) # If regex is matched, return the folder name and the captured date parsed into a datetime object
    return None, None # Fallback to None if no regex match or invalid path

# These are the 6 metric columns which contain pass/warn/fail status 
QC_STATUS_COLS = [
    "per_base_sequence_quality",
    "per_tile_sequence_quality",
    "per_sequence_quality_scores",
    "per_base_n_content",
    "adapter_content",
    "overrepresented_sequences",
]

def compute_failwarn_proportions(df: pd.DataFrame) -> dict:
    """
    Computes overall proportion of samples (%) that are FAIL or WARN across all QC_STATUS_COLS in the multiqc_fastqc.txt file.
    Returns a dictionary with one percentage value per QC_STATUS_COLS metric.
    """
    out = {} # Empty dictionary to store results, e.g. {"per_base_sequence_quality_fail": 2.5, "per_base_sequence_quality_warn": 5.0}
    
    for col in QC_STATUS_COLS: # Loop over each of the 6 QC status columns
        if col in df.columns:
            values = df[col].str.lower() # Convert column values to lowercase and strip whitespace for consistency 
            fail_proportion = 100.0 * (values == "fail").mean() # Calculate proportion of "fail" values as a percentage. count of "fail" divided by total samples *100
            warn_proportion = 100.0 * (values == "warn").mean() # Calculate proportion of "warn" values as a percentage. count of "warn" divided by total samples *100

            out[f"{col}_fail_proportion"] = fail_proportion # Store the fail proportion in the output dictionary with a descriptive key
            out[f"{col}_warn_proportion"] = warn_proportion # Store the warn proportion in the output dictionary with a descriptive key
    
    return out # Return the dictionary containing fail and warn proportions for each QC status metric

def build_csv_from_month(run_type: str, month: str, out_csv: Path) -> Path:
    """
    Build CSV from a single archived month's MultiQC results.
    
    Args:
        run_type: Type of run (genotyping, racp, panels)
        month: YYYY-MM format (e.g., "2025-01")
        out_csv: Output CSV path
    
    Returns:
        Path to the created CSV file
    """
    # Locate the archived MultiQC files for this month
    multiqc_dir = ARCHIVE_BASE / run_type / month / "multiqc_output" / "multiqc_data"
    multiqc_file = multiqc_dir / "multiqc_fastqc.txt"
    sources_file = multiqc_dir / "multiqc_sources.txt"
    
    if not multiqc_file.exists():
        logger.error(f"MultiQC file not found: {multiqc_file}")
        raise SystemExit(f"Error: MultiQC file not found at {multiqc_file}")
    
    if not sources_file.exists():
        logger.error(f"Sources file not found: {sources_file}")
        raise SystemExit(f"Error: Sources file not found at {sources_file}")
    
    logger.info(f"Processing month {month} for run type {run_type}")
    
    # Use the existing build_csv logic but with the archived files
    return build_csv(multiqc_file, sources_file, run_type, None, out_csv, month)

def build_csv(multiqc_file_path: Path, sources_file_path: Path, runtype: str, fromdate: Optional[str], out_csv: Path, archive_month: Optional[str] = None) -> Path:
    """
    Parse MultiQC FastQC results and compute FAIL/WARN proportions per run.
    
    Links samples to their run folders via multiqc_sources.txt, then calculates
    the percentage of samples that failed or warned for each QC metric.
    
    Args:
        multiqc_file_path: Path to multiqc_fastqc.txt
        sources_file_path: Path to multiqc_sources.txt
        runtype: Run type label (e.g., "racp", "genotyping")
        fromdate: Optional cutoff date (YYYY-MM-DD format) to filter runs
        out_csv: Output CSV path
        archive_month: Optional month label (YYYY-MM) for tracking data source
    
    Returns:
        Path to the created CSV file
    """
    #----- Load multiqc_fastqc.txt -----
    df = pd.read_csv(multiqc_file_path, sep="\t")  # reads the multiqc_fastqc.txt file into a pandas DataFrame

    # Looks for "Sample" column in multiqc_fastqc.txt file
    if "Sample" in df.columns:
        sample_column = "Sample"
    else:
        raise SystemExit("Could not find 'Sample' column in multiqc_fastqc.txt file")

    #---- Build sample key to paths mapping -----
    # This connects samples in multiqc_fastqc.txt to their original run folders and dates
    sample_to_paths = build_sample_path_map(Path(sources_file_path))   # {sample_key: [paths,...]}

    #---- Resolve run folder and date for each sample using sample_to_paths -----
    # Resolves run folder and date for each sample in the multiqc_fastqc.txt file by looking up paths in multiqc_sources.txt
    resolved_run_folders: List[Optional[str]] = []
    resolved_run_dates: List[Optional[datetime]] = []

    for sample_id in df[sample_column].astype(str): # Loop through each sample ID, and ensure it's treated as a string
        candidate_paths = sample_to_paths.get(sample_id) # Sample_to_paths is a dictionary based off build_sample_path_map function. Simply, "find me the fastq file paths for this sample, if they exist, otherwise return None"
        
        # Initialise to None in case we don't find anything
        run_folder_for_sample: Optional[str] = None # e.g. 250101_M00000_0001_000000000-ABCDE
        run_date_for_sample: Optional[datetime] = None # run date parsed from run folder (as datetime object)
        
        # If we found any paths for this sample, try to infer run folder and date from them, via infer_run_from_path()
        if candidate_paths:
            for file_path in candidate_paths:
                run_folder_for_sample, run_date_for_sample = infer_run_from_path(file_path) # Uses infer_run_from_path function to extract run folder and date from each file path
                if run_folder_for_sample and run_date_for_sample: # If both run folder and date were successfully extracted, stop looking
                    break
        # Append results (or None) to the cumulative list set up just before this for loop
        resolved_run_folders.append(run_folder_for_sample)
        resolved_run_dates.append(run_date_for_sample)

    #----- Attach folder/date and optional run type to output csv -----
    df["run_folder"] = resolved_run_folders # Add a new column "run_folder" to the DataFrame with the resolved run folder names
    df["run_date"]   = pd.to_datetime(resolved_run_dates).normalize() # Add a new column "run_date" to the DataFrame with the resolved run dates, converted to pandas datetime format

    # If the user specified a --run-type argument, add it as a new column with that value for all rows
    if runtype:
        df["run_type"] = runtype
    
    # Add archive_month column to track which month this data came from
    if archive_month:
        df["archive_month"] = archive_month

    # If no run dates or run folders were resolved, write an empty output file and exit
    if df.empty:
        pd.DataFrame(columns=["run_date", "run_folder", "run_type", "archive_month", "metric", "value(%)"]).to_csv(out_csv, index=False)
        print(f"Wrote 0 rows → {out_csv}")
        return out_csv
    
    # ---- Optional filtering by date () -----
    if fromdate:
        try:
            cutoff = pd.to_datetime(fromdate) # Convert the --fromdate argument to a pandas datetime object
        except ValueError:
            raise SystemExit("Error: --fromdate must be in format YYYY-MM-DD")

        df = df[df["run_date"] >= cutoff] # Filter the DataFrame to only include rows with a run_date on or after the cutoff date

        # If no run dates or run folders remain after filtering, write an empty output file and exit
        if df.empty:
            pd.DataFrame(columns=["run_date", "run_folder", "run_type", "archive_month", "metric", "value(%)"]).to_csv(out_csv, index=False)
            print(f"Wrote 0 rows (after fromdate filter) → {out_csv}")
            return out_csv

    # ---- Compute FAIL/WARN proportions and write output -----
    output_rows = [] # Prepare an empty list to collect all output rows (one row = one run and one metric)

    # Define how to group the dataframe: always by run_date and run_folder, and by run_type if that column exists
    group_columns = ["run_date", "run_folder"] + (["run_type"] if "run_type" in df.columns else [])
    if "archive_month" in df.columns:
        group_columns.append("archive_month")

    # Iterate over each run in the dataframe and group by run_date, run_folder, and optionally run_type
    for group_key, run_subset in df.groupby(group_columns, dropna=False):
        # Handle the case where group_key might be a single value or tuple
        if isinstance(group_key, tuple):
            if len(group_key) == 4:
                run_date, run_folder, run_type, archive_month = group_key
            elif len(group_key) == 3:
                run_date, run_folder, run_type = group_key
                archive_month = None
            else:
                run_date, run_folder = group_key
                run_type = None
                archive_month = None
        else:
            # Single grouping column case
            run_date = group_key
            run_folder = None
            run_type = None
            archive_month = None

        # Compute FAIL/WARN proportions for this run (subset of the above dataframe)
        failwarn_percentages = compute_failwarn_proportions(run_subset)

        # Appends each dictionary entry as a new row to the output_rows list
        for metric_name, percent_value in failwarn_percentages.items():
            output_rows.append({
                "run_date": run_date,
                "run_folder": run_folder,
                "run_type": run_type,
                "archive_month": archive_month,
                "metric": metric_name,
                "value (%)": percent_value
            })

    # Assemble and write
    out = pd.DataFrame(output_rows).sort_values(["run_date", "run_type", "metric"], na_position="last") # Turns the list of dictionary entries into a dataframe and sorts it chronologically by run_date, run_type and metric name
    out.to_csv(out_csv, index=False) # Write the final dataframe to the specified output CSV file
    print(f"Wrote {len(out)} rows → {out_csv}")
    return out_csv

def combine_monthly_csvs(run_type: str, months: List[str], out_csv: Path) -> Path:
    """
    Combine multiple months of CSV data into a single file.
    
    Args:
        run_type: Type of run (genotyping, racp, panels)
        months: List of months in YYYY-MM format (e.g., ["2025-01", "2025-02"])
        out_csv: Output CSV path for combined data
    
    Returns:
        Path to the combined CSV file
    """
    all_dfs = []
    
    for month in months:
        # Create temporary CSV for this month
        temp_csv = out_csv.parent / f"temp_{month}.csv"
        
        try:
            build_csv_from_month(run_type, month, temp_csv)
            df = pd.read_csv(temp_csv)
            all_dfs.append(df)
            logger.info(f"Loaded {len(df)} rows from {month}")
            
            # Clean up temp file
            temp_csv.unlink()
        except Exception as e:
            logger.error(f"Failed to process month {month}: {e}")
            print(f"Warning: Could not process month {month}. Skipping...")
            continue
    
    if not all_dfs:
        logger.error("No data found for any of the specified months")
        raise SystemExit("Error: No data found for any of the specified months")
    
    # Combine all dataframes
    combined_df = pd.concat(all_dfs, ignore_index=True)
    combined_df = combined_df.sort_values(["run_date", "run_type", "metric"], na_position="last")
    combined_df.to_csv(out_csv, index=False)
    
    logger.info(f"Combined {len(months)} months into {out_csv} with {len(combined_df)} total rows")
    print(f"Combined {len(months)} months → {len(combined_df)} rows in {out_csv}")
    
    return out_csv

