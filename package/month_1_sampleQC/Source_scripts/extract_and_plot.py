def table_creation(input_dataframe):
    """
    Creates a table from the main CSV that has one row per run folder, with columns for each metrics fail/warn proportions.
    """

    # Include archive_month in the pivot if it exists
    index_cols = ["run_date", "run_folder", "run_type"]
    if "archive_month" in input_dataframe.columns:
        index_cols.append("archive_month")

    pivoted_dataframe = (
        input_dataframe.pivot_table(
            index=index_cols, # Define the index columns for the pivot table
            columns="metric", # Each metric from the main CSV becomes a separate column in the pivot table
            values="value", # The values to populate the pivot table cells come from the "value" column in the main CSV
            aggfunc="first" # If there are multiple entries for the same run and metric, take the first one to avoid duplicates
            ).reset_index()) # Reset 'index' to turn the index back into regular columns. Without this, run_date, run_folder, and run_type do not appear in the excel output
    
    return pivoted_dataframe # Return the pivoted dataframe for further processing or saving

def order_columns_by_metric_type(columns):
    """
    Orders columns so they are grouped by metric type, with fail first then warn within each group.
    """

    identifier_columns = [col for col in ["run_date", "run_folder", "run_type", "archive_month"] if col in columns] # Ensure that these identifier columns are in their original order and position at the start
    metric_columns = [col for col in columns if col not in identifier_columns] # Extract the metric columns by excluding the identifier columns
    base_metric_name = lambda c: re.sub(r"_(fail|warn)(_proportion)?$", "", c) # Removes the _fail/_warn suffix and optional _proportion suffix to get the base metric name to group metrics
    
    # Group metrics by their base names
    metric_groups = {} # Dictionary to hold groups of metrics by their base names
    for metric in metric_columns: # Loop through each metric column
        metric_groups.setdefault(base_metric_name(metric), []).append(metric) # Group metrics by their base names using setdefault to initialise lists

    # Build the final ordered list: identifier columns first, then each metric group with fail before warn
    ordered_columns = [] # List to hold the final ordered columns
    for group_name in sorted(metric_groups): # Sort the groups alphabetically by their base metric name
        pair = sorted(metric_groups[group_name], key=lambda col: (0 if "_fail" in col else 1, col)) # Sort each group so that fail comes before warn
        ordered_columns.extend(pair) # Add the sorted pair to the final ordered columns list
    
    return identifier_columns + ordered_columns # Return the final list with identifier columns at the start

def format_metric_group_names(column_name):
    """ 
    This function formats metric group names for better readability in Excel headers.
    It also determines whether the metric is a fail or warn proportion for the leaf header.
    """

    human_readable_group_names = column_name.replace("_", " ") # Replace underscores with spaces for readability
    human_readable_group_names = re.sub(r"( proportion| fail| warn)+$", "", human_readable_group_names) # Remove trailing 'proportion', 'fail', or 'warn'

    if column_name.endswith("fail_proportion"): # Establishes whether the metric is a fail or warn proportion for the leaf header
        leaf_name = "Fail proportion %" # If the column name ends with "fail_proportion", set leaf_name accordingly
    elif column_name.endswith("warn_proportion"): # Establishes whether the metric is a fail or warn proportion for the leaf header
        leaf_name = "Warn proportion %" # If the column name ends with "warn_proportion", set leaf_name accordingly
    else:
        leaf_name = "" # Fallback in case neither fail nor warn is found

    return human_readable_group_names, leaf_name # Return the formatted group name

def save_table_excel_pretty_colored(df: pd.DataFrame, outfile: str, decimals=2):
    """
    Exports the dataframe to a formatted Excel file with colors and proper headers.
    """
    
    df_copy = df.copy()
    
    # Round float columns
    for col in df_copy.columns:
        if pd.api.types.is_float_dtype(df_copy[col]):
            df_copy[col] = df_copy[col].round(decimals)
    
    # Split columns into identifier and metric columns
    id_cols = [col for col in ["run_date", "run_folder", "run_type", "archive_month"] if col in df_copy.columns]
   
    
    # Order columns properly
    ordered_cols = order_columns_by_metric_type(df_copy.columns)
    df_copy = df_copy[ordered_cols]
    
    # Create headers
    top_headers = []
    leaf_headers = []
    
    for col in ordered_cols:
        if col in id_cols:
            top_headers.append(col.replace("_", " "))
            leaf_headers.append("")
        else:
            group_name, leaf_name = format_metric_group_names(col)
            top_headers.append(group_name)
            leaf_headers.append(leaf_name)
    
    # Group spans for merging headers
    groups = []
    i = len(id_cols)
    while i < len(top_headers):
        g, j = top_headers[i], i
        while j + 1 < len(top_headers) and top_headers[j + 1] == g:
            j += 1
        groups.append((g, i, j))
        i = j + 1
    
    # Colour palette
    palette = ["#eef7ff", "#fef3e6", "#eef8ee", "#f4ecff", "#fff3fb", "#f0fff2"]
    
    with pd.ExcelWriter(outfile, engine="xlsxwriter") as writer:
        sh = "QC"
        df_copy.to_excel(writer, sheet_name=sh, index=False, header=False, startrow=2)
        wb, ws = writer.book, writer.sheets[sh]
        
        # Define formats
        head_big = wb.add_format({
            "bold": True, "font_size": 12, "align": "center", 
            "valign": "vcenter", "text_wrap": True, "border": 1
        })
        head_leaf = wb.add_format({
            "bold": True, "font_size": 10, "align": "center", 
            "valign": "vcenter", "text_wrap": True, "border": 1
        })
        zebra = wb.add_format({"bg_color": "#EEF2F7"})
        wrap_fmt = wb.add_format({"text_wrap": True, "border": 1})
        num_fmt = wb.add_format({"num_format": "0.00", "border": 1})
        date_fmt = wb.add_format({"num_format": "yyyy-mm-dd", "border": 1})
        
        # Write leaf headers
        for colx, txt in enumerate(leaf_headers):
            if txt and " " not in txt and "\n" not in txt:
                txt = txt + "\n"
            ws.write(1, colx, txt, head_leaf)
        
        # Write identifier column headers (merged vertically)
        for colx, name in enumerate(id_cols):
            ws.merge_range(0, colx, 1, colx, name.replace("_", " "), head_big)
        
        # Write metric group headers with colors
        for gi, (gname, start, end) in enumerate(groups):
            color = palette[gi % len(palette)]
            fmt = wb.add_format({
                "bold": True, "font_size": 12, "align": "center", 
                "valign": "vcenter", "text_wrap": True, "border": 1, 
                "bg_color": color
            })
            ws.merge_range(0, start, 0, end, gname, fmt)
            
            # Color the leaf headers too
            fmt_leaf = wb.add_format({
                "bold": True, "font_size": 10, "align": "center", 
                "valign": "vcenter", "text_wrap": True, "border": 1, 
                "bg_color": color
            })
            for c in range(start, end + 1):
                ws.write(1, c, leaf_headers[c], fmt_leaf)
            
            # Apply background color to data columns
            r0, r1 = 2, 2 + len(df_copy) - 1
            fill = wb.add_format({"bg_color": color, "border": 1})
            ws.conditional_format(r0, start, r1, end, {"type": "no_blanks", "format": fill})
            ws.conditional_format(r0, start, r1, end, {"type": "blanks", "format": fill})
        
        # Set column widths and formats
        for colx, col_name in enumerate(df_copy.columns):
            sample_values = [str(col_name)] + [str(v) for v in df_copy[col_name].head(200)]
            width = min(40, max(10, int(max(len(str(s)) for s in sample_values) * 0.8)))
            
            if col_name.lower() == "run_folder":
                width = max(width, 28)
                ws.set_column(colx, colx, width, wrap_fmt)
            elif col_name.lower() == "run_date":
                ws.set_column(colx, colx, 12, date_fmt)
                for row_idx, value in enumerate(df_copy[col_name], start=2):
                    if pd.notnull(value):
                        ws.write_datetime(row_idx, colx, value, date_fmt)
            elif col_name.lower() == "archive_month":
                ws.set_column(colx, colx, 12, wrap_fmt)
            elif pd.api.types.is_numeric_dtype(df_copy[col_name]):
                ws.set_column(colx, colx, width, num_fmt)
            else:
                ws.set_column(colx, colx, width, wrap_fmt)
        
        # Add zebra striping
        nrows, ncols = df_copy.shape
        ws.conditional_format(2, 0, nrows + 1, ncols - 1, {
            "type": "formula", "criteria": "=MOD(ROW(),2)=0", "format": zebra
        })
        
        # Freeze panes and set row heights
        ws.freeze_panes(2, 0)
        ws.set_row(0, 28)
        ws.set_row(1, 24)

def make_report(long_csv: Path, out_png: Path, run_type: str, metrics: str, out_dir: Path):
    """
    Read long CSV → filter → wide → Excel + PNG into out_dir/
    """
    df = pd.read_csv(long_csv)
    
    # Normalise column names
    df.columns = [c.strip().lower() for c in df.columns]
    if "value (%)" in df.columns and "value" not in df.columns:
        df = df.rename(columns={"value (%)": "value"})
    df["run_date"] = pd.to_datetime(df["run_date"])
    
    # Apply filters from CLI
    keep_types = {t.strip() for t in run_type.split(",")}
    df = df[df.run_type.isin(keep_types)]
    
    if metrics.lower() != "all":
        keep_metrics = {m.strip() for m in metrics.split(",")}
        df = df[df.metric.isin(keep_metrics)]
    
    df = df.sort_values("run_date")
    
    # Create output directory
    out_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate Excel table
    wide = table_creation(df)
    out_xlsx = out_dir / f"{out_png.stem}_table.xlsx"
    save_table_excel_pretty_colored(wide, str(out_xlsx), decimals=2)
    
    # Generate PNG plot with month separators
    df["value"] = pd.to_numeric(df["value"], errors="coerce")
    metrics_list = sorted(df["metric"].unique())
